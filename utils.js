function greet(name) {
    return `Hello, ${name}!`;
}

function add(a, b) {
    return a + b;
}

console.log(greet("Developer"));
console.log("Sum:", add(10, 20));

function now(name) {
    return `Heyy, ${name}!`;
}

function minus(a, b) {
    return a - b;
}

console.log(now("Developer"));
console.log("Difference:", minus(100, 20));